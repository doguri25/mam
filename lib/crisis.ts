export const crisisOf = (text: string): CrisisId[] => CRISIS.filter((g) => g.words.test(text)).map((g) => g.id);
export const crisisById = (id: string) => CRISIS.find((g) => g.id === id);

// 챗봇에 넣을 글(고정 안내를 그대로)
export function crisisText(g: CrisisGuide): string {
  return [
    `[대응 안내] ${g.title} (기준 ${CHECKED})`,
    `가장 먼저: ${g.first}`,
    ...g.steps.map((s, i) => `${i + 1}. ${s}`),
    `해 줄 말: ${g.say.join(" / ")}`,
    `피할 말: ${g.avoid.join(" / ")}`,
    ...g.notes.map((n) => `- ${n}`),
    `연락처: ${g.calls.map((c) => `${c.label} ${c.num}${c.note ? `(${c.note})` : ""}`).join(", ")}`,
    `출처: ${g.src.join("; ")}`,
  ].join("\n");
}
