// ── 찾기: 글자 둘씩 묶은 조각(바이그램)이 얼마나 겹치는지로 점수를 매긴다(형태소 분석 없이 한국어에 무난) ──
const WORD = /[\p{L}\p{N}]+/gu;
export function grams(text: string): Set<string> {
  const out = new Set<string>();
  for (const w of text.toLowerCase().match(WORD) ?? []) {
    if (w.length === 1) continue;
    for (let i = 0; i < w.length - 1; i++) out.add(w.slice(i, i + 2));
  }
  return out;
}
// 여러 글 가운데 물음에 맞는 정도(0~1쯤). 흔한 조각(「사회」「정서」처럼 거의 모든 글에 있는 것)은 덜 쳐 주고(IDF),
// 제목·꼬리표에서 찾으면 더 쳐 준다.
export function rank(query: string, items: { head: string; body: string }[]): number[] {
  const q = [...grams(query)];
  if (!q.length || !items.length) return items.map(() => 0);
  const gs = items.map((it) => ({ h: grams(it.head), b: grams(it.body) }));
  const n = items.length;
  const w = q.map((g) => {
    const df = gs.filter((x) => x.h.has(g) || x.b.has(g)).length;
    return df ? Math.log(1 + n / df) : 0;
  });
  const total = w.reduce((a, b) => a + b, 0) || 1;
  return gs.map((x) => q.reduce((s, g, i) => s + w[i] * ((x.h.has(g) ? 1.5 : 0) + (x.b.has(g) ? 1 : 0)), 0) / total);
}

export function searchKb(query: string, n = 3, min = 0.7): KbCard[] {
  const s = rank(query, KB.map((c) => ({ head: `${c.title} ${c.tags.join(" ")}`, body: c.text })));
  const top = Math.max(0, ...s);
  return KB.map((c, i) => ({ c, s: s[i] }))
    .filter((x) => x.s >= min && x.s >= top * 0.6) // 가장 잘 맞는 것보다 한참 처지는 카드는 빼서 AI가 엉뚱한 자료를 끌어오지 않게
    .sort((a, b) => b.s - a.s)
    .slice(0, n)
    .map((x) => x.c);
}
